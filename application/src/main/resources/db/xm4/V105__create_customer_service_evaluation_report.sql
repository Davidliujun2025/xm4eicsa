CREATE TABLE IF NOT EXISTS customer_service_evaluation_report (
    id BIGINT NOT NULL AUTO_INCREMENT,
    conversation_id VARCHAR(64) NOT NULL,
    session_task_id BIGINT NOT NULL,
    operator_id VARCHAR(64) NOT NULL,
    platform VARCHAR(32) NOT NULL,
    total_score INT NOT NULL,
    service_attitude_score INT NOT NULL,
    problem_solving_score INT NOT NULL,
    empathy_score INT NOT NULL,
    compliance_score INT NOT NULL,
    conversion_guidance_score INT NOT NULL,
    response_efficiency_score INT NOT NULL,
    dimension_weights_json JSON NOT NULL,
    strengths TEXT NOT NULL,
    problems TEXT NOT NULL,
    suggestions TEXT NOT NULL,
    forbidden_hit_count INT NOT NULL DEFAULT 0,
    forbidden_words_json JSON NOT NULL,
    transcript LONGTEXT NOT NULL,
    total_tokens INT NOT NULL DEFAULT 0,
    generated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_evaluation_conversation (conversation_id),
    KEY idx_evaluation_operator_time (operator_id, generated_at),
    KEY idx_evaluation_operator_score (operator_id, total_score),
    KEY idx_evaluation_operator_platform (operator_id, platform),
    CONSTRAINT fk_evaluation_conversation
        FOREIGN KEY (session_task_id) REFERENCES conversation(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
